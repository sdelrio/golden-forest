// Resolves 'mdi:apps' / 'apps' / 'game-icons:castle' to a bundled icon object.
// Unknown names return undefined so they render nothing instead of throwing.
// shortcut: these names are not in their icon set and render nothing (they were
// already blank before bundling): check-double, code-compare, code-pull-request,
// desktop, golang, photo, route, scalpel, shield-cog, token, vial, video-cut,
// zap, game-icons:dice-twenty-faces, game-icons:scroll.
export default function resolveIcon(name) {
  if (!name) return undefined;
  const [set, icon] = (name.includes(':') ? name : `mdi:${name}`).split(':');
  return (ICONS[set] || {})[icon];
}
